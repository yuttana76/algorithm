# ================= Binary Search (การค้นหาแบบแบ่งครึ่ง) ================= #
# กฎเหล็ก: ข้อมูลในลิสต์ "ต้องเรียงลำดับแล้ว (Sorted)" เท่านั้น!
# หลักการ: ตรวจค่าตรงกลาง (mid) แล้วตัดพื้นที่การค้นหาทิ้งทีละครึ่งในทุกรอบ

def binary_search(nums: list[int], target: int) -> int:
    # (1) กำหนดขอบซ้ายสุดของช่วงการค้นหาเริ่มต้นที่ index แรก (0)
    left = 0
    # (2) กำหนดขอบขวาสุดของช่วงการค้นหาเริ่มต้นที่ index สุดท้าย
    right = len(nums) - 1
    # (3) วนลูปตราบใดที่กรอบการค้นหายังเหลือสมาชิกอย่างน้อย 1 ตัว
    #     * ต้องใช้ <= เพราะตอน left == right ยังเหลือตัวสุดท้ายให้ตรวจอีก 1 ตัว
    i = 0
    while left <= right:
        # (4) หาตำแหน่งกึ่งกลาง (ใช้ // เพื่อหารปัดเศษลงเป็นจำนวนเต็ม)
        #     ใช้ left + (right - left) // 2 เป็น Best Practice กัน integer overflow ในภาษาอื่น
        mid = left + (right - left) // 2
        
        print(i)

        # (5)-(6) ถ้าค่าตรงกลางตรงกับเป้าหมาย คืน index ทันทีและจบฟังก์ชัน
        if nums[mid] == target:
            return mid

        # (7)-(8) ถ้าค่าตรงกลาง "น้อยกว่า" เป้าหมาย แสดงว่าคำตอบอยู่ฝั่งขวาเท่านั้น
        #         ตัดฝั่งซ้ายรวมถึง mid ทิ้งทั้งหมด โดยขยับ left ไปที่ mid + 1 (ป้องกัน Infinite Loop)
        elif nums[mid] < target:
            left = mid + 1

        # (9)-(10) ถ้าค่าตรงกลาง "มากกว่า" เป้าหมาย แสดงว่าคำตอบอยู่ฝั่งซ้ายเท่านั้น
        #          ตัดฝั่งขวารวมถึง mid ทิ้งทั้งหมด โดยขยับ right มาที่ mid - 1 (ป้องกัน Infinite Loop)
        else:
            right = mid - 1
        
        i = i+1

    # (11) หลุดลูป (left > right) แปลว่าตัดพื้นที่จนหมดแล้วไม่เจอข้อมูล คืน -1
    return -1


# --- ทดลองเรียกใช้งาน (ลิสต์ต้องเรียงจากน้อยไปมาก!) ---
numbers = [2, 5, 8, 12, 16, 23, 38, 56, 72, 91]
result = binary_search(numbers, 72)
print("เจอที่ตำแหน่ง (index):", result)  # Output: 5


# ================= สรุป Big-O Complexity ================= #
# - Time Complexity (เวลาทำงาน):
#   * Best Case  : O(1)      -> เจอตรงกลางตั้งแต่รอบแรก
#   * Worst Case : O(log n)  -> ตัดข้อมูลทิ้งทีละครึ่งไปเรื่อยๆ (ข้อมูล 1 ล้านตัว ตรวจไม่เกิน 20 รอบ!)
#   * Average    : O(log n)
#
# - Space Complexity (หน่วยความจำที่ใช้เพิ่ม):
#   * O(1) (Constant Space)  -> ใช้แค่ตัวแปร left, right, mid ไม่ได้สร้างลิสต์เพิ่ม
#
# - ตัวอย่างการไล่รอบ (Dry Run) เมื่อ target = 23:
#   รอบที่ 1: left=0, right=9 -> mid=4 -> nums[4]=16 < 23 -> ขยับ left = 5
#   รอบที่ 2: left=5, right=9 -> mid=7 -> nums[7]=56 > 23 -> ขยับ right = 6
#   รอบที่ 3: left=5, right=6 -> mid=5 -> nums[5]=23 == 23 -> เจอ! คืนค่า 5

